/// [s] en NFC pour les lettres latines accentuées (le reste est inchangé).
String nfc(String s) {
  if (s.isEmpty) return s;
  final unites = s.runes.toList();
  final sortie = StringBuffer();
  var i = 0;
  while (i < unites.length) {
    final base = String.fromCharCode(unites[i]);
    if (i + 1 < unites.length) {
      final compose = _composees['$base${String.fromCharCode(unites[i + 1])}'];
      if (compose != null) {
        sortie.write(compose);
        i += 2;
        continue;
      }
    }
    sortie.write(base);
    i++;
  }
  return sortie.toString();
}
